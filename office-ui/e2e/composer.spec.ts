import { expect, test } from '@playwright/test';

test('black theme and composer preserve drafts, grow, and submit once by keyboard', async ({ page }, testInfo) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  let submissions = 0;
  let payload: { question?: string; mode?: string } = {};
  await page.route('**/api/runs/start', async route => {
    submissions++;
    payload = route.request().postDataJSON();
    await route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ message: 'Test provider unavailable. Your draft is kept.' }) });
  });
  await page.goto('/?token=e2e-office-token-0123456789');
  await expect(page.getByTestId('ws-status')).toHaveText(/live/);
  expect(await page.locator('body').evaluate(el => getComputedStyle(el).backgroundColor)).toBe('rgb(0, 0, 0)');
  const field = page.getByTestId('question-input');
  if (!await field.isVisible()) await page.getByRole('button', { name: '＋ New task', exact: true }).click();
  await field.focus();
  await field.press('Control+Enter');
  expect(submissions).toBe(0);
  await expect(page.getByTestId('start-run-btn')).toBeDisabled();
  const initialHeight = await field.evaluate(el => el.getBoundingClientRect().height);
  const draft = 'Research a simple task dashboard.\n' + Array.from({ length: 9 }, (_, i) => `${i + 1}. Keep this requirement clear and easy to use.`).join('\n');
  await field.fill(draft);
  await expect(field).toBeFocused();
  await expect(page.locator('.composer-writing')).toContainText('Writing');
  expect(await field.evaluate(el => el.getBoundingClientRect().height)).toBeGreaterThan(initialHeight);
  await expect(page.locator('.character-count')).toHaveAttribute('aria-label', `${draft.length} of 20000 characters`);
  await page.getByTestId('area-coding_room').click();
  await expect(field).toHaveValue(draft);
  await page.getByRole('button', { name: 'Give your council a task', exact: false }).click();
  await expect(field).toBeHidden();
  await page.getByRole('button', { name: '＋ New task', exact: true }).click();
  await expect(field).toBeFocused();
  await expect(field).toHaveValue(draft);
  await page.getByLabel('Workflow', { exact: true }).selectOption('discuss');
  await field.press('Control+Enter');
  await expect(page.getByRole('alert')).toContainText('Your draft is kept');
  expect(submissions).toBe(1);
  expect(payload).toMatchObject({ question: draft, mode: 'discuss' });
  await expect(field).toHaveValue(draft);
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await field.fill('');
  await field.blur();
  await expect(page.locator('.typed-hint')).toContainText('Research the best approach');
  await page.screenshot({ path: testInfo.outputPath('black-composer-mobile.png'), fullPage: true });
  expect(errors).toEqual([]);
});
